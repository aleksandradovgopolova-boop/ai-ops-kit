"""Человеческая «передняя дверь» CLI (#675 Human API).

Команды, которыми говорит ЧЕЛОВЕК-владелец продукта: короткий набор, видимый ПЕРВЫМ экраном при
`ai-ops` без аргументов и при `ai-ops help`. Остальные интенты — рабочая механика кита: они
полностью работают и вызываются как раньше, но не вываливаются на человека стеной из 36 команд и
30 флагов (их показывает `ai-ops help --all`). Это ВИТРИНА, а не ограничение доступа.

Вынесено из `ai_ops_cli` отдельным модулем, чтобы вход-CLI не рос как монолит: `handle()` возвращает
код выхода, если вызов — это запрос помощи, иначе None (и CLI разбирает интент как обычно).
"""
from __future__ import annotations

# Набор мал НАМЕРЕННО и проверяется тестом (дверь не должна тихо разрастаться обратно в стену):
# человек, который не знает внутренней механики кита, должен понять, что попросить, с первого экрана.
HUMAN_INTENTS = ("onboard", "discuss", "do", "status", "next", "explain", "inbox", "review",
                 "products", "readout")

# Короткие человеческие подписи — СМЫСЛ, без внутренних терминов (полное описание с флагами даёт
# `ai-ops help --all` и сама команда).
_HUMAN_LABELS = {
    "onboard":  "познакомить кита с этим репозиторием",
    "discuss":  "обсудить идею, прежде чем делать",
    "do":       'сделать задачу целиком:  ai-ops do "что нужно"',
    "status":   "что сейчас происходит",
    "next":     "что взять следующим и почему",
    "explain":  "что с моей задачей прямо сейчас",
    "inbox":    "что ждёт моего решения — одной очередью",
    "review":   "независимо проверить сделанное",
    "products": "состояние всех продуктов разом",
    "readout":  "что получилось после релиза",
}


def render(intents, full=False):
    """Текст двери. `intents` — реестр INTENTS кита (имя -> (описание, handler, needs_task))."""
    lines = ["AI Ops — что можно попросить у кита.", "", "Основные команды:"]
    for name in HUMAN_INTENTS:
        lines.append(f"  ai-ops {name:<9} {_HUMAN_LABELS.get(name, intents[name][0])}")
    if not full:
        lines += ["", "Полный список команд и флаги — ai-ops help --all"]
    else:
        lines += ["", "Продвинутое (рабочая механика кита — работает как раньше):"]
        for name, meta in intents.items():
            if name not in HUMAN_INTENTS:
                lines.append(f"  ai-ops {name:<9} {meta[0]}")
    return "\n".join(lines)


def handle(argv, intents):
    """Если вызов — запрос человеческой двери (пусто или `help`), напечатать её и вернуть код выхода.
    Иначе вернуть None (CLI разбирает интент как обычно)."""
    if not argv or argv[0] == "help":
        print(render(intents, full=("--all" in argv)))
        return 0
    return None
