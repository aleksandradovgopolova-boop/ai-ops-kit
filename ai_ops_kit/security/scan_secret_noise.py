"""Что НЕ является секретом: плейсхолдеры и адреса на своей машине.

Сателлит `security_scan` (фасад импортирует отсюда `looks_like_placeholder` и `is_loopback_dsn`).
Появился не из вкуса к дроблению: после разбора ложных блокировок (#1138) сканер перешагнул порог
монолита в 700 строк — ратчет размера модуля сказал об этом до слияния.

ЗДЕСЬ ТОЛЬКО ТО, ЧТО ГОВОРИТ «ЭТО НЕ СЕКРЕТ» ПО САМОМУ ЗНАЧЕНИЮ. Признак «где лежит» сюда не
относится намеренно: код в документации не исполняется, а пароль в документации — всё ещё утёкший
пароль (см. сторож `test_security_scan_secret_false_blocks`).

Своей точки входа у сателлита нет осознанно: он обслуживает сканер, а не запускается сам.
"""
from __future__ import annotations

import re

# Плейсхолдеры и ссылки на env — не секрет.
#
# СПИСОК БЫЛ АНГЛОЯЗЫЧНЫМ И ASCII-ONLY (#1138). Класс `[a-z_]` физически не мог сматчить кириллицу,
# поэтому «ПАРОЛЬ» в инструкции по развёртыванию читался как утечка; слова `pass`/`password` в списке
# тоже не было, хотя `user:pass@host` — самая частая форма плейсхолдера в строке подключения.
# Вердикт независимого судьи 24.09.2026 по реальному продукту: 5 находок из 17 — ровно этот класс.
_PLACEHOLDER = re.compile(
    r"(?i)(x{6,}|\$\{?[a-z_]+\}?|<[a-z_ -]+>|your[_-]?|example|changeme|placeholder|env\["
    r"|^pass(?:word)?$|^pwd$|^secret$|^token$"          # ровно слово, а не «passw0rd-от-базы»
    r"|^[А-ЯЁ]{4,}$|^пароль$|^секрет$|^токен$"          # кириллица: «ПАРОЛЬ», «СЕКРЕТ»
    # Тестовая заглушка ЦЕЛИКОМ из слов через дефис: `test-session-token`. Узко намеренно — цифры,
    # верхний регистр и подчёркивания НЕ проходят, поэтому `test_sk_live_A1b2...` остаётся флагом:
    # префикс `test` не делает материал ключа безобидным.
    r"|^(?:test|fake|dummy|sample)-[a-z-]+$)")

# ХОСТ НА ПЕТЛЕ — НЕ УТЕЧКА. Строка подключения к `localhost` не даёт доступа, который надо отзывать:
# пароль там либо от контейнера в CI, либо от машины разработчика. Вердикт судьи 24.09.2026 — 8
# находок из 17 ровно такие: дефолты сервис-контейнеров GitHub Actions, примеры локального запуска.
#
# ГРАНИЦА УЗКАЯ: правило применяется ТОЛЬКО к строке подключения. Любой другой формат (ключ, токен,
# JWT) остаётся находкой независимо от хоста — ключ остаётся ключом и на localhost.
_LOOPBACK_DSN_HOST = re.compile(
    r"@(?:localhost|127(?:\.\d{1,3}){3}|\[::1\]|::1)(?::\d+)?(?:[/?#]|$)", re.I)


def looks_like_placeholder(value: str) -> bool:
    """Значение — заглушка, а не секрет."""
    return bool(_PLACEHOLDER.search(value))


def is_loopback_dsn(tail: str) -> bool:
    """Хвост строки подключения ведёт на свою машину."""
    return bool(_LOOPBACK_DSN_HOST.search(tail))


# Материал ключа после заголовка PEM: base64-тело. Его отсутствие означает, что назван ФОРМАТ, а не
# выдан ключ — так заголовок и стоит в CHANGELOG, в манифесте и в отчёте аудита.
_PEM_BODY = re.compile(r"[A-Za-z0-9+/]{20,}")

# Сколько строк после заголовка считать телом ключа. Настоящий PEM начинает тело сразу; больший
# запас начал бы цеплять соседний текст.
PEM_LOOKAHEAD = 2


def pem_header_has_body(tail_of_line: str, next_lines: list) -> bool:
    """За заголовком PEM идут байты ключа — значит это ключ, а не упоминание формата.

    ТЕЛО ИЩЕТСЯ И НА СЛЕДУЮЩИХ СТРОКАХ, а не только в хвосте текущей: в настоящем PEM-файле
    заголовок стоит отдельной строкой, и проверка только своей строки пропустила бы ровно тот
    случай, ради которого правило существует.
    """
    return any(_PEM_BODY.search(t) for t in [tail_of_line, *next_lines])
