"""Запуск команды: где он поверхность внедрения, а где безопасен по конструкции.

Сателлит `security_scan` (фасад импортирует отсюда `child_process_imported` и `surface_lines`).

ЧТО ПРАВИЛО ГАРАНТИРУЕТ — И ЧЕГО НЕ ГАРАНТИРУЕТ. Флаг снимается, когда в самой строке вызова видно,
что ИМЯ БИНАРЯ (`argv[0]`) записано литералом и оболочка не участвует: подставить ДРУГУЮ КОМАНДУ
туда нельзя. Это и есть внедрение команды — класс, ради которого правило существует.

Внедрение АРГУМЕНТОВ этим не покрывается и никогда не покрывалось: `execFileSync("git", args)` с
пользовательским `args` остаётся опасным (`git -c core.sshCommand=…`), и сканер этого не видит.
Формулировка «исполнится ровно то, что написано в файле» была бы НЕВЕРНОЙ — зафиксировано только
имя бинаря. Независимое ревью 25.09.2026 поймало это преувеличение в первой версии; оно исправлено
здесь и в changelog, а не сглажено. Частично класс всё же ловится: если среди аргументов ВИДЕН флаг,
которым бинарю передают код или команду (`-c`, `-e`, `--eval`, `-exec`, `--to-command`), вызов
остаётся поверхностью независимо от имени бинаря.

ПОЧЕМУ НЕ ПОМЕТИТЬ КАТАЛОГ `scripts/` ОБВЯЗКОЙ. Так было бы дешевле и так делать ЗАПРЕЩЕНО
(записано в `planning/plan.yaml` решением владельца): в `scripts/` живёт и эксплуатация — бэкап
базы, деплой, — а отказ от этого признака был осознанным в #1146. Это была бы подгонка замера под
планку. Точность правила работает и в боевом коде, а не только в каталоге с известным именем.

ЧТО ОСТАЁТСЯ ФЛАГОМ:
  * `exec`/`execSync` — ВСЕГДА через оболочку;
  * имя бинаря не литерал (переменная, шаблон с подстановкой, выражение);
  * литерал называет ОБОЛОЧКУ (`sh`, `bash`, `cmd`…) — в любом регистре и по любому пути;
  * среди аргументов виден флаг передачи кода/команды;
  * в опциях есть `shell` в любой форме, кроме доказанно ложной, — или россыпь `...opts`,
    внутри которой `shell` может оказаться.

Своей точки входа у сателлита нет осознанно: он обслуживает сканер, а не запускается сам.
"""
from __future__ import annotations

import re

CHILD_PROCESS_IMPORT = re.compile(
    r"""(?:require\s*\(\s*['"](?:node:)?child_process['"]|"""
    r"""from\s+['"](?:node:)?child_process['"]|"""
    r"""import\s+[^\n;]*['"](?:node:)?child_process['"])""")

# `spawn`/`fork` добавлены по разбору 24.09 (#1146): в ЕДИНСТВЕННОМ боевом месте исполнения команд
# на реальном продукте правило знало только `exec*` — и сканер называл строку `import`, а не строку
# вызова. Правило, существующее ради АДРЕСА, на боевом адресе адреса не давало.
_ВЫЗОВ = re.compile(r"\b(exec|execSync|execFile|execFileSync|spawn|spawnSync|fork)\s*\(")

# Семейство, которое ВСЕГДА идёт через оболочку: первый аргумент — целая командная строка.
_ЧЕРЕЗ_ОБОЛОЧКУ = frozenset({"exec", "execSync"})

# R-40, ВТОРОЙ ЗАХОД (#1112). `\b` в `_ВЫЗОВ` стоит между точкой и `e`, поэтому правило матчит и
# `.exec(` РЕГУЛЯРНОГО ВЫРАЖЕНИЯ. Чинится ПОЛУЧАТЕЛЕМ, а не сужением правила: `.exec(` с неизвестным
# получателем по-прежнему флагается — получатель может оказаться обёрткой над child_process.
#
# ПОЧЕМУ `/` ПЕРЕД `.exec(` ОДНОЗНАЧЕН: в JavaScript косая черта вплотную перед `.exec(` может быть
# только концом литерала регулярного выражения — деление `.exec(` за собой не ведёт.
_ПОЛУЧАТЕЛЬ_РЕГУЛЯРКА = re.compile(r"(?:/|\bnew\s+RegExp\s*\([^\n]*\))\s*\.\s*exec\s*\(")
_ИМЯ_РЕГУЛЯРКИ = re.compile(
    r"""(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:/|new\s+RegExp\s*\()""")

# Оболочки: литеральное имя здесь НЕ делает запуск безопасным — оболочка и есть способ внедрения.
# Сравнение регистронезависимое: на macOS и Windows файловая система тоже не различает регистр.
_ОБОЛОЧКИ = frozenset({"sh", "bash", "dash", "zsh", "ksh", "csh", "tcsh", "fish",
                       "cmd", "cmd.exe", "powershell", "powershell.exe", "pwsh",
                       "env", "xargs", "nohup", "timeout", "sudo", "su", "ssh"})
# Интерпретаторы: им короткие флаги можно СКЛЕИВАТЬ (`python3 -Sc`), поэтому для них правило шире.
_ИНТЕРПРЕТАТОРЫ = frozenset({"node", "nodejs", "deno", "bun", "python", "python2", "python3",
                             "ruby", "perl", "php", "osascript", "rscript", "lua"})

# ФЛАГИ ПЕРЕДАЧИ КОДА ИЛИ КОМАНДЫ. Форма `--eval=code` и склейка коротких флагов (`-Sc`) — рабочие
# формы, а не экзотика: обе проверены запуском. Хвост требует КОНЦА ТОКЕНА или `=`, поэтому
# `ffmpeg -c:v libx264` не матчится: там после `-c` идёт двоеточие, то есть флаг другой.
_КОНЕЦ_ТОКЕНА = r"(?=[=\s\"'`,\]\)]|$)"
_ФЛАГ_КОДА = re.compile(
    r"(?<![\w-])(?:--?(?:eval|command|to-command|exec)|-[ecp])" + _КОНЕЦ_ТОКЕНА)
_ФЛАГ_КОДА_СКЛЕЙКОЙ = re.compile(r"(?<![\w-])-[A-Za-z]*[ecp][A-Za-z]*" + _КОНЕЦ_ТОКЕНА)

# ОПЦИЯ `shell` ПРИЗНАЁТСЯ В ЛЮБОЙ ФОРМЕ, КРОМЕ ДОКАЗАННО ЛОЖНОЙ. Прежде проверялся литеральный
# `shell: true` — и молчали `shell: "/bin/sh"` (документированная опция Node, это ОБОЛОЧКА),
# `shell: !0`, `shell: opts.shell`, `{ ...opts }`. Нашло независимое ревью.
_SHELL_ЛОЖЬ = re.compile(r"""['"]?\bshell['"]?\s*:\s*(?:false|!1|0|undefined|null)\s*[,}]""")
_SHELL_КЛЮЧ = re.compile(r"""['"]?\bshell['"]?\s*:""")
# РОССЫПЬ СЧИТАЕТСЯ ТОЛЬКО В САМОМ ОБЪЕКТЕ ОПЦИЙ, а не где угодно в вызове. Два соседних случая на
# реальном продукте показали, почему нужна именно глубина:
#   * `[…, "run", ...tests]` — распаковка АРГУМЕНТОВ, опций там нет вовсе;
#   * `{ cwd: ROOT, env: { ...process.env } }` — распаковка ОКРУЖЕНИЯ, вложенная на уровень глубже;
#     `shell` в неё попасть не может.
# Опасна россыпь на ПЕРВОМ уровне фигурных скобок (`{ ...opts }`): туда `shell` приходит целиком.

# Сколько символов после открывающей скобки считать вызовом. Настоящий вызов укладывается с
# запасом; ограничение нужно, чтобы незакрытая скобка не утащила разбор через весь файл.
_ОКНО = 400


def without_regexp_exec(line: str, regexp_names: frozenset) -> str:
    """Убрать из строки вызовы `.exec(` у регулярных выражений — остальное трогать нельзя."""
    out = _ПОЛУЧАТЕЛЬ_РЕГУЛЯРКА.sub("", line)
    for name in regexp_names:
        out = re.sub(r"\b" + re.escape(name) + r"\s*\.\s*exec\s*\(", "", out)
    return out


def child_process_imported(text: str) -> bool:
    """Файл подключает `child_process` — только тогда `exec`-вызовы в нём считаем командами."""
    return bool(CHILD_PROCESS_IMPORT.search(text))


def blank_string_contents(text: str) -> str:
    """Содержимое строковых литералов -> пробелы; длина и переводы строк сохраняются.

    ЗАЧЕМ ЭТО НУЖНО. Текст внутри строки — не код. Без такого скелета фраза
    `const HINT = "используйте spawn('git', args)"` считалась ВЫЗОВОМ: этого хватало, чтобы снять
    флаг со строки импорта, и настоящее `cp["exec"](userCmd)` в том же файле переставало блокировать
    гейт. То есть управлять вердиктом можно было, дописав безобидную строку (нашло независимое
    ревью). Тот же класс, что закрывали для комментариев в #1146, только через другую дверь.

    Внутри шаблонного литерала участки `${...}` — это КОД, и они сохраняются: иначе вызов, стоящий
    в подстановке, пропал бы из разбора.
    """
    out = list(text)
    i, n, кавычка, глубина_подстановки = 0, len(text), None, 0
    while i < n:
        сим = text[i]
        if кавычка:
            if сим == "\\":
                i += 2
                continue
            if кавычка == "`" and text.startswith("${", i):
                глубина_подстановки += 1
                i += 2
                continue
            if глубина_подстановки:
                if сим == "}":
                    глубина_подстановки -= 1
                i += 1
                continue                       # внутри ${...} — код, не трогаем
            if сим == кавычка:
                кавычка = None
            elif сим != "\n":
                out[i] = " "
            i += 1
            continue
        if сим in "'\"`":
            кавычка = сим
            глубина_подстановки = 0
        i += 1
    return "".join(out)


def _границы_вызова(скелет: str, начало: int) -> int:
    """Смещение закрывающей скобки вызова (или предела окна). Скобки считаются по СКЕЛЕТУ —
    скобка внутри строкового литерала не должна сбивать счёт."""
    глубина, предел = 0, min(len(скелет), начало + _ОКНО)
    for i in range(начало, предел):
        if скелет[i] == "(":
            глубина += 1
        elif скелет[i] == ")":
            глубина -= 1
            if глубина == 0:
                return i
    return предел


def _первый_аргумент(окно: str) -> tuple:
    """-> (вид, значение). Вид: `литерал`, `execPath` или `неизвестно`.

    Литералом считается ТОЛЬКО строка в кавычках без подстановки: шаблон с `${...}` — это уже
    значение, собранное из данных, и его содержимое неизвестно на момент чтения кода.
    """
    текст = окно.lstrip()
    if not текст:
        return ("неизвестно", "")
    if текст.startswith("process.execPath"):
        return ("execPath", "node")
    кавычка = текст[0]
    if кавычка not in "\"'`":
        return ("неизвестно", "")
    i, значение = 1, []
    while i < len(текст):
        сим = текст[i]
        if сим == "\\":
            i += 2
            continue
        if сим == кавычка:
            собрано = "".join(значение)
            if кавычка == "`" and "${" in собрано:
                return ("неизвестно", "")       # шаблон с подстановкой — не литерал
            return ("литерал", собрано)
        значение.append(сим)
        i += 1
    return ("неизвестно", "")                    # кавычка не закрылась в окне


def _имя_бинаря(значение: str) -> str:
    """Последний сегмент пути без каталогов и без регистра: `/bin/BASH` -> `bash`."""
    return значение.replace("\\", "/").rsplit("/", 1)[-1].strip().lower()


def _россыпь_в_опциях(скелет: str) -> bool:
    """`...` на ПЕРВОМ уровне фигурных скобок вызова — объект опций собран из чужого значения."""
    глубина = 0
    for i, сим in enumerate(скелет):
        if сим == "{":
            глубина += 1
        elif сим == "}":
            глубина -= 1
        elif глубина == 1 and скелет.startswith("...", i):
            return True
    return False


def launch_is_a_surface(функция: str, окно: str, окно_скелет: str = None) -> bool:
    """Этот запуск команды — поверхность внедрения?

    `окно` — текст аргументов как он написан (флаги живут ВНУТРИ строковых литералов, поэтому их
    ищем здесь). `окно_скелет` — он же с погашенным содержимым строк, по нему ищутся опции: слово
    `shell` внутри строки опцией не является. По умолчанию скелет считается сам.

    Ответ «нет» даётся ТОЛЬКО когда безопасность видна по конструкции в самом вызове.
    """
    if функция in _ЧЕРЕЗ_ОБОЛОЧКУ:
        return True                              # оболочка участвует всегда
    скелет = blank_string_contents(окно) if окно_скелет is None else окно_скелет
    if _россыпь_в_опциях(скелет):
        return True                              # `{ ...opts }` — внутри может оказаться `shell`
    if _SHELL_КЛЮЧ.search(скелет) and not _SHELL_ЛОЖЬ.search(скелет):
        return True                              # `shell` в любой форме, кроме доказанно ложной
    вид, значение = _первый_аргумент(окно)
    if вид == "неизвестно":
        return True                              # имя бинаря неизвестно на момент чтения кода
    бинарь = _имя_бинаря(значение)
    if бинарь in _ОБОЛОЧКИ:
        return True
    if _ФЛАГ_КОДА.search(окно):
        return True                              # бинарю передают код или команду — видно прямо тут
    if (бинарь in _ИНТЕРПРЕТАТОРЫ or вид == "execPath") and _ФЛАГ_КОДА_СКЛЕЙКОЙ.search(окно):
        return True                              # интерпретаторам короткие флаги можно склеивать
    return False


def surface_lines(код: str) -> tuple:
    """-> (найдены ли вызовы вообще, номера строк-поверхностей).

    ДВА ОТВЕТА, А НЕ ОДИН, И ЭТО НЕСУЩЕЕ РАЗЛИЧИЕ. Флаг на строке `import child_process` снимается
    только когда вызовы НАЙДЕНЫ И РАЗОБРАНЫ: тогда про каждый известно, поверхность он или нет.
    Если вызовов не нашлось вовсе — а такое бывает при переименовании (`const run = execFile;`
    дальше `run(cmd)`), — строка импорта остаётся флагом: мы не разобрали ничего, и молчание здесь
    означало бы «не проверено», выданное за «чисто».

    РАЗБИРАЮТСЯ ВСЕ ВЫЗОВЫ НА СТРОКЕ, а не первый. Прежде стоял `search`, и безопасный вызов слева
    гасил опасный справа (`execFileSync("git", a); execSync(userCmd);`) — нашло независимое ревью.
    Та же ошибка уже ловилась в сканере секретов; здесь она повторилась в другом файле.

    На вход идёт текст БЕЗ КОММЕНТАРИЕВ (#1146): закомментированный вызов не исполняется, а раз
    найденный вызов снимает флаг со строки импорта, такой «вызов» уводил бы судью с настоящей
    строки — и этим можно было бы управлять снаружи, дописав комментарий.
    """
    имена_регулярок = frozenset(_ИМЯ_РЕГУЛЯРКИ.findall(код))
    # Скелет строится ОДИН раз на файл: по нему ищутся вызовы и считаются скобки.
    скелет = blank_string_contents(код)
    строки, строки_скелета = код.splitlines(), скелет.splitlines()
    смещения, позиция = [], 0
    for строка in строки:
        смещения.append(позиция)
        позиция += len(строка) + 1
    найдено, были_вызовы = [], False
    for номер, (строка, строка_скелета) in enumerate(zip(строки, строки_скелета), 1):
        очищенная = without_regexp_exec(строка_скелета, имена_регулярок)
        if not _ВЫЗОВ.search(очищенная):
            continue
        for m in _ВЫЗОВ.finditer(строка_скелета):
            # Вызов регулярного выражения — не команда: проверяем по очищенному тексту, что этот
            # конкретный `.exec(` не снят как `RE.exec(`.
            if m.group(1) == "exec" and not _ВЫЗОВ.search(
                    without_regexp_exec(строка_скелета[:m.end()], имена_регулярок)):
                continue
            были_вызовы = True
            старт = смещения[номер - 1] + m.end() - 1
            конец = _границы_вызова(скелет, старт)
            if launch_is_a_surface(m.group(1), код[старт + 1:конец], скелет[старт + 1:конец]):
                найдено.append(номер)
                break                            # на строке довольно одного адреса
    return были_вызовы, найдено
