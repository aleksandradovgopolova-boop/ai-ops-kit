"""Что в файле НЕ является кодом продукта: проза, комментарии и обвязка.

Сателлит `security_scan` (фасад импортирует отсюда `PROSE_SUFFIXES` и `blank_comments`). Появился
не из вкуса к дроблению: после того как комментарии перестали считаться кодом (#1112), сам сканер
перешагнул порог монолита в 700 строк — ратчет размера модуля сказал об этом до слияния.

Своей точки входа у сателлита нет осознанно: он обслуживает сканер, а не запускается сам.
"""
from __future__ import annotations

# Проза — не исполняемый код. `dangerouslySetInnerHTML`, упомянутый в CHANGELOG, ничего не
# исполняет; флаг на нём — не осторожность, а шум.
PROSE_SUFFIXES = (".md", ".rst", ".txt")

# КОММЕНТАРИЙ — ТОЖЕ ПРОЗА, а отличается от прозы только тем, что лежит внутри файла с кодом.
# Замер 23.09.2026 (#1112): 6 флагов `react_dangerous_html` из 8 стояли НЕ НА КОДЕ, и один — на
# комментарии, утверждавшем ОБРАТНОЕ («рендер React-элементами без dangerouslySetInnerHTML»).
# Отсечение по расширению файла этого не ловит: `.ts` с комментарием расширением не отличается от
# `.ts` с кодом.
#
# СОДЕРЖИМОЕ КОММЕНТАРИЕВ ЗАМЕНЯЕТСЯ ПРОБЕЛАМИ, а не вырезается: номера строк в находках обязаны
# остаться прежними, иначе судья пойдёт по неверному адресу.
#
# РАЗБОР ОШИБАЕТСЯ В БЕЗОПАСНУЮ СТОРОНУ. Кавычки отслеживаются, чтобы `"https://x"` не был принят за
# комментарий; на регулярке вида `/['"]/` разбор может решить, что строка открыта, и тогда он просто
# НЕ вычистит комментарий — то есть ошибётся в сторону лишнего флага, а не пропуска.
LINE_COMMENT_BY_SUFFIX = {
    ".py": ("#",), ".pyi": ("#",), ".sh": ("#",), ".bash": ("#",), ".zsh": ("#",),
    ".yaml": ("#",), ".yml": ("#",), ".toml": ("#",), ".rb": ("#",), ".pl": ("#",),
    ".js": ("//",), ".mjs": ("//",), ".cjs": ("//",), ".jsx": ("//",),
    ".ts": ("//",), ".mts": ("//",), ".cts": ("//",), ".tsx": ("//",),
    ".java": ("//",), ".go": ("//",), ".rs": ("//",), ".c": ("//",), ".cc": ("//",),
    ".cpp": ("//",), ".h": ("//",), ".hpp": ("//",), ".cs": ("//",), ".kt": ("//",),
    ".swift": ("//",), ".scala": ("//",), ".vue": ("//",), ".svelte": ("//",),
    ".php": ("//", "#"),
}
BLOCK_COMMENT_SUFFIXES = frozenset({
    ".js", ".mjs", ".cjs", ".jsx", ".ts", ".mts", ".cts", ".tsx", ".java", ".go", ".rs",
    ".c", ".cc", ".cpp", ".h", ".hpp", ".cs", ".kt", ".swift", ".scala", ".php",
    ".vue", ".svelte", ".css", ".scss", ".less",
})


def _suffix_of(path: str) -> str:
    tail = path.replace("\\", "/").rsplit("/", 1)[-1]
    return "." + tail.rsplit(".", 1)[-1].lower() if "." in tail else ""


# ЛИТЕРАЛ РЕГУЛЯРНОГО ВЫРАЖЕНИЯ — НЕ КОММЕНТАРИЙ. `const r = /[//]/; spawn(bin, argv);` —
# косая внутри класса символов читалась как начало комментария, и ОСТАТОК СТРОКИ пропадал вместе
# с настоящим вызовом. Нашло независимое ревью (третий круг #1161): пока рядом стоял безопасный
# вызов, флаг держался за него, а как только правило научилось такие вызовы прощать, опора исчезла.
#
# ГДЕ `/` НАЧИНАЕТ РЕГУЛЯРКУ, А ГДЕ ДЕЛИТ. Различить их по-настоящему нельзя без разбора языка,
# поэтому берётся признанная эвристика: регулярка может стоять там, где ожидается ЗНАЧЕНИЕ, то есть
# после открывающей скобки, запятой, оператора или начала строки; после имени, числа, `)` или `]`
# стоит деление. ОШИБКА ЗДЕСЬ ДЕШЕВА В ОДНУ СТОРОНУ: приняв комментарий за регулярку, разбор просто
# НЕ вычистит его — это лишний флаг. Приняв регулярку за комментарий, он съедает код — это пропуск.
# Эвристика сдвигает ошибку в первую сторону.
_ЗНАЧЕНИЕ_ОЖИДАЕТСЯ_ПОСЛЕ = frozenset("(,=:[!&|?{};+-*%~^<>") | {"\n", "\r", ""}
# Где литералы регулярных выражений вообще бывают. Языки стилей сюда НЕ входят (см. ниже).
REGEXP_LITERAL_SUFFIXES = frozenset({
    ".js", ".mjs", ".cjs", ".jsx", ".ts", ".mts", ".cts", ".tsx", ".vue", ".svelte",
})


def _регулярка_здесь(text: str, i: int, предыдущий: str) -> bool:
    """`/` в позиции i открывает литерал регулярного выражения, а не делит и не начинает комментарий."""
    if text.startswith("//", i) or text.startswith("/*", i):
        return False
    return предыдущий in _ЗНАЧЕНИЕ_ОЖИДАЕТСЯ_ПОСЛЕ


def _конец_регулярки(text: str, i: int) -> int:
    """Смещение сразу за литералом. Класс символов `[...]` учитывается: внутри него `/` не закрывает.
    Литерал не переживает перевод строки — иначе одна косая ослепила бы разбор до конца файла."""
    j, в_классе, n = i + 1, False, len(text)
    while j < n:
        c = text[j]
        if c == "\\":
            j += 2
            continue
        if c == "\n":
            return i + 1                      # не закрылся на своей строке — это было не регулярка
        if c == "[":
            в_классе = True
        elif c == "]":
            в_классе = False
        elif c == "/" and not в_классе:
            return j + 1
        j += 1
    return i + 1


def blank_comments(text: str, path: str) -> str:
    """Содержимое комментариев -> пробелы. Длина и переводы строк сохраняются."""
    suffix = _suffix_of(path)
    line_markers = LINE_COMMENT_BY_SUFFIX.get(suffix)
    block = suffix in BLOCK_COMMENT_SUFFIXES
    # РЕГУЛЯРНЫХ ЛИТЕРАЛОВ НЕТ В ЯЗЫКАХ СТИЛЕЙ, и эвристика «косая после `%` открывает регулярку»
    # там не может быть права никогда: `calc(100% / 3)` она читала бы как начало литерала и съедала
    # настоящий код до следующей косой. Нашло независимое ревью.
    регулярки = suffix in REGEXP_LITERAL_SUFFIXES
    if not line_markers and not block:
        return text
    out = list(text)
    i, n, quote = 0, len(text), None
    предыдущий = ""                           # последний значимый символ вне строк и комментариев
    while i < n:
        ch = text[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote or (ch == "\n" and quote != "`"):
                quote = None          # строка не переживает перевод строки (кроме шаблонной)
            i += 1
            continue
        if ch in "'\"`":
            quote = ch
            i += 1
            continue
        if регулярки and ch == "/" and _регулярка_здесь(text, i, предыдущий):
            конец = _конец_регулярки(text, i)
            if конец > i + 1:
                # СОДЕРЖИМОЕ ЛИТЕРАЛА ГАСИТСЯ, а не просто пропускается. Внутри регулярки кавычка —
                # часть образца, а не начало строки: `/`/` и `/"/` рядом на одной строке «открывали»
                # и «закрывали» строку, код между ними исчезал из разбора, и разбор считал себя
                # состоявшимся. Чётность бродячих кавычек обходила проверку «кавычка закрылась» —
                # нашло независимое ревью на четвёртом круге. Гасим содержимое, оставляя косые:
                # правило R-40 узнаёт `/…/.exec(` по ним, а длина и переводы строк сохраняются.
                for k in range(i + 1, конец - 1):
                    if out[k] != "\n":
                        out[k] = " "
                предыдущий = "/"
                i = конец
                continue
        if block and text.startswith("/*", i):
            end = text.find("*/", i + 2)
            end = n if end == -1 else end + 2
            for k in range(i, end):
                if out[k] != "\n":
                    out[k] = " "
            i = end
            continue
        if line_markers and any(text.startswith(mark, i) for mark in line_markers):
            end = text.find("\n", i)
            end = n if end == -1 else end
            for k in range(i, end):
                out[k] = " "
            i = end
            continue
        if not ch.isspace():
            предыдущий = ch
        elif ch == "\n":
            предыдущий = "\n"
        i += 1
    return "".join(out)


