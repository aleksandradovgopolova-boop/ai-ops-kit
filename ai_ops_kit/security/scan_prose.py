VENDOR_PREFIX = ".ai/managed/"


_TEST_DIRS = ("tests/", "test/", "__tests__/", "e2e/", "__mocks__/")
_TEST_MARKERS = (".test.", ".spec.")
_TOOL_CONFIGS = ("vite.config.", "vitest.config.", "jest.config.", "webpack.config.",
                 "rollup.config.", "playwright.config.", "eslint.config.", "babel.config.",
                 "tsup.config.", "esbuild.config.")


def area_of(path: str) -> str:
    """`product` — боевой путь, `harness` — тесты и конфиги, `vendor` — установленная копия кита."""
    rel = path.replace("\\", "/")
    # `./.ai/managed/...` ловится ВТОРОЙ ветвью (в нём есть `/.ai/managed/`), поэтому отдельной
    # нормализации `./` здесь нет: она была бы кодом, который ничего не решает и ничем не сторожится.
    if rel.startswith(VENDOR_PREFIX) or f"/{VENDOR_PREFIX}" in rel:
        return "vendor"
    name = rel.rsplit("/", 1)[-1]
    if any(name.startswith(cfg) for cfg in _TOOL_CONFIGS):
        return "harness"
    if any(marker in name for marker in _TEST_MARKERS):
        return "harness"
    if any(rel.startswith(d) or f"/{d}" in rel for d in _TEST_DIRS):
        return "harness"
    return "product"


def blank_string_contents(text: str, шаблоны: bool = True) -> tuple:
    """-> (скелет, состоялся ли разбор). Содержимое строковых литералов -> пробелы; длина и
    переводы строк сохраняются.

    ВТОРОЙ ОТВЕТ — ОТ ТРЕТЬЕГО КРУГА РЕВЬЮ, И ОН ЗАКРЫВАЕТ КЛАСС, А НЕ ОЧЕРЕДНОЙ ВХОД В НЕГО.
    Две предыдущие починки latали конкретные символы — сначала `"` и `'` в литерале регулярного
    выражения, потом обратную кавычку, — и каждый раз находился следующий. Корень один: разбор
    ПОЛАГАЛСЯ на то, что кавычка когда-нибудь закроется. Если она не закрылась к концу файла,
    скелет недостоверен, и «вызовов не нашли» здесь означает «ослепли», а не «чисто».

    «РАЗБОР СОСТОЯЛСЯ» ЗНАЧИТ «НИ РАЗУ НЕ УГАДЫВАЛИ»: кавычка закрылась своей парой, а не концом
    файла и не переводом строки.

    ЗАЧЕМ ЭТО НУЖНО. Текст внутри строки — не код. Без такого скелета фраза
    `const HINT = "используйте spawn('git', args)"` считалась ВЫЗОВОМ: этого хватало, чтобы снять
    флаг со строки импорта, и настоящее `cp["exec"](userCmd)` в том же файле переставало блокировать
    гейт. То есть управлять вердиктом можно было, дописав безобидную строку (нашло независимое
    ревью). Тот же класс, что закрывали для комментариев в #1146, только через другую дверь.

    Внутри шаблонного литерала участки `${...}` — это КОД, и они сохраняются: иначе вызов, стоящий
    в подстановке, пропал бы из разбора.
    
    ДВА ПРОЧТЕНИЯ ОДНОГО ТЕКСТА. `шаблоны=True` — обратная кавычка открывает шаблонную строку, как
    в JavaScript. `шаблоны=False` — она обычный символ, как в тексте разметки JSX. Отличить их без
    разбора языка нельзя, поэтому сканер читает файл ОБА раза и доверяет только тому, в чём оба
    прочтения согласны.
    """
    out = list(text)
    i, n, кавычка, глубина_подстановки = 0, len(text), None, 0
    оборвана = False                          # была ли строка закрыта переводом строки
    while i < n:
        сим = text[i]
        if кавычка:
            if сим == "\\":
                i += 2
                continue
            if кавычка == "`" and text.startswith("${", i):
                глубина_подстановки += 1
                i += 2
                continue
            if глубина_подстановки:
                if сим == "}":
                    глубина_подстановки -= 1
                i += 1
                continue                       # внутри ${...} — код, не трогаем
            if сим == кавычка:
                кавычка = None
            elif сим == "\n" and кавычка != "`":
                # СТРОКА, ЗАКРЫТАЯ ПЕРЕВОДОМ СТРОКИ, А НЕ СВОЕЙ КАВЫЧКОЙ, — ЭТО ПРИЗНАННАЯ
                # НЕОДНОЗНАЧНОСТЬ, А НЕ РАЗБОР. В валидном JavaScript строка всегда закрывается на
                # своей строке, поэтому такое закрытие означает, что кавычка строкой не была:
                # апостроф в тексте JSX (`<p>don't</p>`), кавычка в литерале регулярного выражения
                # (`return /"/.test(s)`). Прежде этот случай не оставлял следа — оба прочтения
                # давали одинаковый скелет, согласие достигалось, и остаток строки исчезал вместе с
                # настоящим вызовом (нашло независимое ревью, седьмой круг).
                оборвана = True
                # СТРОКА НЕ ПЕРЕЖИВАЕТ ПЕРЕВОД СТРОКИ (кроме шаблонной). Без этого кавычка внутри
                # литерала регулярного выражения — `s.replace(/"/g, …)`, идиома из любого проекта —
                # «открывала строку» до конца файла, и ВЕСЬ код после неё исчезал из разбора:
                # безопасный вызов выше снимал флаг с импорта, а настоящая поверхность ниже
                # становилась невидимой. Нашло независимое ревью; ровно так же ошибается в
                # безопасную сторону разбор комментариев в `scan_prose`.
                кавычка = None
            elif сим != "\n":
                out[i] = " "
            i += 1
            continue
        if сим in "'\"`":
            # УГАДЫВАТЬ, ШАБЛОН ЭТО ИЛИ ТЕКСТ РАЗМЕТКИ, ЗДЕСЬ НЕЛЬЗЯ. Позиционная эвристика,
            # написанная для `/`, обратной кавычке не годится: шаблон законен и после `return`, и
            # после имени (тегированный шаблон), и после `)`. С ней содержимое настоящих шаблонов
            # читалось как КОД (нашло независимое ревью, шестой круг). Неоднозначность решается не
            # здесь, а сравнением ДВУХ прочтений — см. `шаблоны` и `scan_exec_call.surface_lines`.
            if сим != "`" or шаблоны:
                кавычка = сим
                глубина_подстановки = 0
        i += 1
    return "".join(out), (кавычка is None and not оборвана)
