#!/usr/bin/env bash
# Исполнить CommitContract на том, что реально уходит в коммит.
#
# ЗАЧЕМ (замер 12.08.2026). `commit_policy.check_commit` существует с v3.19.0 и НЕ ЗАПУСКАЛСЯ
# нигде: ни в хуках, ни в CI. На коммите 4a231ae, где `git add -A` унёс в чужой коммит фикс
# CI-шаблона и research-скан, контракт даёт `broad_scope` — «затронуто 5 верхнеуровневых каталогов,
# похоже на несколько задач в одном коммите». Проверка была права и молчала, потому что её не звали.
#
# Стадия `commit-msg`, а не `pre-commit`: контракту нужны И файлы, И текст сообщения (часть правил —
# про сообщение: заглушки, секреты, ссылка на WorkItem и evidence). На стадии `pre-commit` сообщения
# ещё нет, поэтому половина контракта там не исполнилась бы — а половина проверки хуже отсутствующей:
# она создаёт видимость полной.
#
# Сегодня контракт СОВЕТУЕТ (enforce: advise): rc берётся из `allowed`, то есть блокируют только
# настоящие нарушения, а советы печатаются. Ужесточение — решение владельца
# (planning/plan.yaml -> session-coordination), правило репозитория: сначала field evidence.
set -euo pipefail
cd "$(dirname "$0")/.."

MSG_FILE="${1:-}"
if [ -z "$MSG_FILE" ] || [ ! -f "$MSG_FILE" ]; then
  echo "commit-contract: не передан файл сообщения коммита — хук вызван не со стадии commit-msg." >&2
  exit 2
fi

# Только проиндексированное: контракт обязан судить то, что уходит в историю, а не рабочее дерево.
# Без `mapfile`: на macOS /bin/bash — это 3.2, где его нет, и хук падал бы с «command not found»
# у каждого, кто работает на маке. Замерено при первом же запуске.
#
# `COMMIT_CONTRACT_FILES` — ШОВ ДЛЯ ТЕСТОВ, а не настройка. Хук работает с индексом ЭТОГО
# репозитория, поэтому тест иначе зависел бы от того, что в индексе прямо сейчас: он проходил при
# непустом и молча выходил раньше проверок при чистом. Это ровно тот класс — результат зависит от
# окружения, а не от предмета. Продакшн-путь не меняется: pre-commit переменную не задаёт.
# Образец приёма — `runner` в orchestrator_providers («runner заменяет subprocess.run, а не весь
# вызов — production-path проходит в selftest»).
FILES=()
if [ -n "${COMMIT_CONTRACT_FILES:-}" ]; then
  for _f in $COMMIT_CONTRACT_FILES; do
    FILES+=("$_f")
  done
else
  while IFS= read -r _f; do
    [ -n "$_f" ] && FILES+=("$_f")
  done < <(git diff --cached --name-only --diff-filter=ACMR)
fi
if [ ${#FILES[@]} -eq 0 ]; then
  exit 0            # merge/amend без изменений индекса — судить нечего
fi

# Пустая строка и комментарии git из сообщения не входят в предмет проверки.
MESSAGE="$(grep -v '^#' "$MSG_FILE" | sed '/^[[:space:]]*$/d')"

# `PYTHON` — чтобы хук можно было ПРОВЕРИТЬ тем же интерпретатором, что тесты. Значение по
# умолчанию совпадает с остальными локальными хуками репозитория (`python3`).
PYTHON="${PYTHON:-python3}"

# «Контракт не смог запуститься» ОБЯЗАНО отличаться от «контракт нашёл нарушение»: иначе первое
# читается как второе, и наоборот — а это тот самый класс, из-за которого контракт вообще не
# исполнялся. Проверяем предпосылку явно и говорим, что делать.
if ! "$PYTHON" -c 'import yaml' 2>/dev/null; then
  echo "CommitContract НЕ ВЫПОЛНЕН: у '$PYTHON' нет pyyaml — охват коммита и осмысленность" >&2
  echo "сообщения сейчас НЕ проверены (это не «нарушений нет»)." >&2
  echo "Поставить: $PYTHON -m pip install pyyaml   (или PYTHON=<интерпретатор> с pyyaml)" >&2
  exit 1
fi

# ПЕРЕСЕЧЕНИЕ С ЧУЖОЙ ЗАЯВКОЙ. Замер 26 коммитов дня показал, чем плохой коммит отличался от
# законных: НЕ шириной. Под `broad_scope` попали четыре, и по делу — только один (`4a231ae`, куда
# `git add -A` унёс чужую работу); остальные три были правками «код + тесты + запись находки».
# Поэтому ширина осталась советом, а проверяется то, что действительно различало случаи: попали ли
# в коммит файлы из области, которую заявила ДРУГАЯ сессия. Ответ у кита есть — реестр активных
# работ. Предупреждение, не блокировка: заявка может быть протухшей, а хук, который мешает без
# основания, обходят `--no-verify`, и тогда не работает уже ничего.
if [ -z "${COMMIT_CONTRACT_SKIP_CLAIMS:-}" ]; then
  _REG=$("$PYTHON" -c 'from ai_ops_kit.lifecycle import active_work as a; print(a.shared_registry_path())' 2>/dev/null || true)
  if [ -n "$_REG" ] && [ -f "$_REG" ]; then
    # области = верхнеуровневые каталоги проиндексированного (реестр ведётся в этих терминах)
    _AREAS=$(printf '%s\n' "${FILES[@]}" | awk -F/ '{print (NF>1 ? $1"/" : $1)}' | sort -u | paste -sd, -)
    "$PYTHON" -m ai_ops_kit.lifecycle.active_work check "$_REG" --areas "$_AREAS" 2>/dev/null \
      | grep -v "пересечений по зонам" || true
  fi
fi

"$PYTHON" ai_ops_kit/engops/commit_policy.py . --files "${FILES[@]}" --message "$MESSAGE"
